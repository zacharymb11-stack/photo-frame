/* Alarm clock for Photo Frame.
   Ringtones are generated by the app itself (Web Audio), so nothing needs downloading.
   Note: like any web app on an iPad, alarms only ring while Photo Frame is open on screen. */
(function () {
  'use strict';

  const STORE = 'photoframe.alarms.v1';
  const DAYS = ['Sun', 'Mon', 'Tue', 'Wed', 'Thu', 'Fri', 'Sat'];
  const TONES = [
    { id: 'chimes', name: 'Gentle chimes' },
    { id: 'marimba', name: 'Marimba' },
    { id: 'harp', name: 'Harp' },
    { id: 'birds', name: 'Birdsong' },
    { id: 'waves', name: 'Ocean waves' },
    { id: 'bell', name: 'Classic bell' },
    { id: 'beep', name: 'Digital beep' }
  ];
  const $ = (id) => document.getElementById(id);
  const pad = (n) => (n < 10 ? '0' : '') + n;

  let state = { alarms: [], fired: {}, snooze: null };
  try {
    const s = JSON.parse(localStorage.getItem(STORE));
    if (s && s.alarms) state = { alarms: s.alarms, fired: s.fired || {}, snooze: s.snooze || null };
  } catch (e) {}
  function save() { try { localStorage.setItem(STORE, JSON.stringify(state)); } catch (e) {} }

  let opts = { is24: () => false, onRing: null };
  const fmt = (h, m) => opts.is24() ? pad(h) + ':' + pad(m) : (h % 12 || 12) + ':' + pad(m) + (h < 12 ? ' AM' : ' PM');
  function daysText(a) {
    if (!a.days.length) return 'Once';
    if (a.days.length === 7) return 'Every day';
    const s = a.days.slice().sort().join(',');
    if (s === '1,2,3,4,5') return 'Weekdays';
    if (s === '0,6') return 'Weekends';
    return a.days.slice().sort().map((d) => DAYS[d]).join(' ');
  }

  // ================================================================
  // Sound: build each ringtone as a short audio clip, then loop it.
  // ================================================================
  let ctx = null, unlocked = false;
  const buffers = {};
  function audio() {
    if (!ctx) {
      const AC = window.AudioContext || window.webkitAudioContext;
      if (!AC) return null;
      ctx = new AC();
      // newer iOS: play even when the ringer switch is on silent
      try { if (navigator.audioSession) navigator.audioSession.type = 'playback'; } catch (e) {}
    }
    return ctx;
  }
  // iPads only allow sound after a tap, so every tap tries to unlock audio.
  function unlock() {
    const c = audio();
    if (!c) return;
    if (c.state === 'suspended' && c.resume) c.resume();
    if (!unlocked) {
      const b = c.createBuffer(1, 1, 22050), s = c.createBufferSource();
      s.buffer = b; s.connect(c.destination);
      if (s.start) s.start(0); else s.noteOn(0);
    }
    unlocked = c.state === 'running' || unlocked;
    setTimeout(() => { unlocked = c.state === 'running'; updateHint(); }, 200);
  }
  ['touchend', 'click', 'keydown'].forEach((ev) => document.addEventListener(ev, unlock, true));

  function note(name) {
    const n = { C: 0, D: 2, E: 4, F: 5, G: 7, A: 9, B: 11 }[name[0]];
    const oct = +name[name.length - 1];
    return 440 * Math.pow(2, (n + (oct + 1) * 12 - 69) / 12);
  }
  // add a tone made of sine partials: [[ratio, amplitude, decaySeconds], ...]
  function tone(data, sr, start, freq, amp, partials, attack) {
    const len = Math.min(data.length - Math.floor(start * sr), Math.floor(sr * 3));
    const s0 = Math.floor(start * sr);
    attack = attack || 0.004;
    for (let p = 0; p < partials.length; p++) {
      const f = freq * partials[p][0], a = amp * partials[p][1], dec = partials[p][2];
      if (f > sr / 2) continue;
      const w = 2 * Math.PI * f / sr;
      for (let i = 0; i < len; i++) {
        const t = i / sr;
        const env = (t < attack ? t / attack : 1) * Math.exp(-t / dec);
        if (env < 0.0005 && t > attack) break;
        data[s0 + i] += a * env * Math.sin(w * i);
      }
    }
  }
  function pluck(data, sr, start, freq, amp) {          // Karplus-Strong string
    const N = Math.max(2, Math.round(sr / freq)), buf = new Float32Array(N);
    for (let i = 0; i < N; i++) buf[i] = Math.random() * 2 - 1;
    const s0 = Math.floor(start * sr), len = Math.min(data.length - s0, Math.floor(sr * 2.5));
    let idx = 0, prev = 0;
    for (let i = 0; i < len; i++) {
      const cur = buf[idx];
      const next = 0.996 * 0.5 * (cur + prev);
      prev = cur; buf[idx] = next;
      idx = (idx + 1) % N;
      data[s0 + i] += amp * cur;
    }
  }
  function build(id) {
    const c = audio();
    if (!c) return null;
    if (buffers[id]) return buffers[id];
    const sr = c.sampleRate;
    const lens = { chimes: 3.6, marimba: 2.8, harp: 3.2, birds: 4.5, waves: 8, bell: 2.4, beep: 1.2 };
    const len = Math.floor(sr * lens[id]);
    const buf = c.createBuffer(1, len, sr), d = buf.getChannelData(0);
    if (id === 'chimes') {
      const bell = [[1, 1, 1.6], [2.76, 0.35, 0.9], [5.4, 0.15, 0.5], [8.9, 0.07, 0.3]];
      ['E6', 'G6', 'C7', 'G6'].forEach((n, i) => tone(d, sr, i * 0.45, note(n), 0.22, bell));
    } else if (id === 'marimba') {
      const mar = [[1, 1, 0.45], [4, 0.25, 0.12], [10, 0.06, 0.05]];
      ['C5', 'E5', 'G5', 'A5', 'G5', 'E5', 'G5', 'C6'].forEach((n, i) => tone(d, sr, i * 0.19, note(n), 0.3, mar));
    } else if (id === 'harp') {
      ['C4', 'E4', 'G4', 'C5', 'E5', 'G5', 'C6'].forEach((n, i) => pluck(d, sr, i * 0.13, note(n), 0.28));
    } else if (id === 'birds') {
      let t = 0.1;
      while (t < lens.birds - 0.6) {
        const n = 3 + Math.floor(Math.random() * 4), base = 2600 + Math.random() * 1500;
        for (let k = 0; k < n; k++) {
          const dur = 0.05 + Math.random() * 0.06, s0 = Math.floor(t * sr), L = Math.floor(dur * sr);
          let ph = 0;
          for (let i = 0; i < L && s0 + i < len; i++) {
            const q = i / L;
            const f = base * (1 + 0.35 * Math.sin(q * Math.PI) + 0.08 * Math.sin(q * 40));
            ph += 2 * Math.PI * f / sr;
            d[s0 + i] += 0.25 * Math.sin(q * Math.PI) * (Math.sin(ph) + 0.15 * Math.sin(2 * ph));
          }
          t += dur + 0.03 + Math.random() * 0.04;
        }
        t += 0.25 + Math.random() * 0.6;
      }
    } else if (id === 'waves') {
      let lp = 0, b0 = 0, b1 = 0, b2 = 0;
      for (let i = 0; i < len; i++) {
        const w = Math.random() * 2 - 1;          // pink-ish noise
        b0 = 0.997 * b0 + w * 0.029; b1 = 0.985 * b1 + w * 0.032; b2 = 0.95 * b2 + w * 0.048;
        const pink = b0 + b1 + b2 + w * 0.02;
        const q = i / len, swell = 0.2 + 0.8 * Math.pow(Math.sin(Math.PI * q), 2);
        const cut = 0.02 + 0.12 * swell;
        lp += cut * (pink - lp);
        d[i] = lp * swell * 2.2;
      }
    } else if (id === 'bell') {
      const bell = [[1, 1, 0.25], [2.4, 0.5, 0.15], [4.1, 0.3, 0.08]];
      for (let t = 0; t < 1.5; t += 1 / 18) tone(d, sr, t, 2100, 0.12, bell, 0.001);
    } else if (id === 'beep') {
      for (let k = 0; k < 4; k++) {
        const s0 = Math.floor(k * 0.14 * sr), L = Math.floor(0.08 * sr);
        for (let i = 0; i < L; i++) {
          const e = Math.min(1, i / 60, (L - i) / 60);
          d[s0 + i] += 0.22 * e * (Math.sin(2 * Math.PI * 3800 * i / sr) + 0.2 * Math.sin(2 * Math.PI * 7600 * i / sr));
        }
      }
    }
    // keep it from clipping
    let peak = 0;
    for (let i = 0; i < len; i++) peak = Math.max(peak, Math.abs(d[i]));
    if (peak > 0.95) for (let i = 0; i < len; i++) d[i] *= 0.95 / peak;
    buffers[id] = buf;
    return buf;
  }

  let playing = null;
  function play(id, loop, rampFrom) {
    stopSound();
    const c = audio();
    if (!c) return;
    if (c.state === 'suspended' && c.resume) c.resume();
    const buf = build(id);
    if (!buf) return;
    const src = c.createBufferSource(), gain = c.createGain();
    src.buffer = buf; src.loop = !!loop;
    src.connect(gain); gain.connect(c.destination);
    const now = c.currentTime;
    gain.gain.setValueAtTime(rampFrom === undefined ? 1 : rampFrom, now);
    if (rampFrom !== undefined) gain.gain.linearRampToValueAtTime(1, now + 20);   // gets louder over 20 seconds
    if (src.start) src.start(0); else src.noteOn(0);
    playing = { src: src, gain: gain };
    if (!loop) src.onended = () => { if (playing && playing.src === src) playing = null; };
  }
  function stopSound() {
    if (playing) { try { playing.src.stop(0); } catch (e) {} playing = null; }
  }

  // ================================================================
  // Checking the time
  // ================================================================
  const dateKey = (d) => d.getFullYear() + '-' + (d.getMonth() + 1) + '-' + d.getDate();
  let ringing = null, ringTimer = null;

  function check() {
    if (ringing) return;
    const now = new Date();
    if (state.snooze && Date.now() >= state.snooze.at) {
      const a = state.alarms.find((x) => x.id === state.snooze.id);
      state.snooze = null; save();
      if (a) { ring(a); return; }
    }
    for (const a of state.alarms) {
      if (!a.on) continue;
      const target = new Date(now); target.setHours(a.h, a.m, 0, 0);
      const diff = now - target;
      if (diff < 0 || diff > 3 * 60000) continue;           // ring if it's due (or was due in the last 3 minutes)
      if (a.days.length && a.days.indexOf(now.getDay()) < 0) continue;
      const key = dateKey(now) + ' ' + a.h + ':' + a.m;
      if (state.fired[a.id] === key) continue;
      state.fired[a.id] = key;
      if (!a.days.length) a.on = false;
      save(); renderList();
      ring(a);
      return;
    }
  }

  function ring(a) {
    ringing = a;
    $('ringTime').textContent = fmt(a.h, a.m);
    $('ringLabel').textContent = a.label || 'Alarm';
    $('alarmRing').className = 'ring';
    play(a.tone, true, a.tone === 'bell' || a.tone === 'beep' ? 0.4 : 0.15);
    updateHint();
    if (opts.onRing) opts.onRing();
    clearTimeout(ringTimer);
    ringTimer = setTimeout(stopRing, 10 * 60000);          // give up after 10 minutes
  }
  function stopRing() {
    stopSound();
    ringing = null;
    clearTimeout(ringTimer);
    $('alarmRing').className = 'ring hidden';
    renderNext();
  }
  function snooze() {
    const a = ringing;
    stopRing();
    if (a) { state.snooze = { id: a.id, at: Date.now() + (a.snooze || 9) * 60000 }; save(); }
    renderNext();
  }
  function updateHint() {
    const c = ctx;
    $('ringHint').textContent = ringing && (!c || c.state !== 'running') ? 'Tap the screen to hear the alarm sound.' : '';
  }

  // ================================================================
  // Next alarm
  // ================================================================
  function nextAlarm() {
    const now = new Date();
    let best = null;
    if (state.snooze) best = { at: new Date(state.snooze.at), a: state.alarms.find((x) => x.id === state.snooze.id), snoozed: true };
    state.alarms.forEach((a) => {
      if (!a.on) return;
      for (let k = 0; k < 8; k++) {
        const d = new Date(now); d.setDate(now.getDate() + k); d.setHours(a.h, a.m, 0, 0);
        if (d <= now) continue;
        if (a.days.length && a.days.indexOf(d.getDay()) < 0) continue;
        if (!best || d < best.at) best = { at: d, a: a };
        break;
      }
    });
    return best;
  }
  function renderNext() {
    const n = nextAlarm();
    let text = '';
    if (n && n.a) {
      const today = new Date(), tom = new Date(); tom.setDate(today.getDate() + 1);
      const day = n.at.toDateString() === today.toDateString() ? 'today' : n.at.toDateString() === tom.toDateString() ? 'tomorrow' : DAYS[n.at.getDay()];
      text = (n.snoozed ? 'Snoozed until ' : 'Next alarm: ') + fmt(n.at.getHours(), n.at.getMinutes()) + ' ' + day;
    }
    const el = $('nextAlarm');
    if (el) el.textContent = text || 'No alarms set.';
    const badge = $('stageAlarm');
    if (badge) {
      badge.textContent = n && n.a ? '⏰ ' + fmt(n.at.getHours(), n.at.getMinutes()) : '';
      badge.className = n && n.a ? 'stage-alarm' : 'stage-alarm hidden';
    }
  }

  // ================================================================
  // Alarm list and editor
  // ================================================================
  function renderList() {
    const list = $('alarmList');
    list.innerHTML = '';
    state.alarms.slice().sort((x, y) => (x.h * 60 + x.m) - (y.h * 60 + y.m)).forEach((a) => {
      const row = document.createElement('div');
      row.className = 'alarm-row' + (a.on ? '' : ' off');
      row.innerHTML = '<div class="alarm-main"><div class="alarm-time"></div><div class="alarm-sub"></div></div><button type="button" class="alarm-toggle"></button>';
      row.querySelector('.alarm-time').textContent = fmt(a.h, a.m);
      const tn = TONES.find((t) => t.id === a.tone);
      row.querySelector('.alarm-sub').textContent = (a.label ? a.label + ' · ' : '') + daysText(a) + ' · ' + (tn ? tn.name : '');
      const tg = row.querySelector('.alarm-toggle');
      tg.textContent = a.on ? 'On' : 'Off';
      tg.className = 'alarm-toggle' + (a.on ? ' on' : '');
      tg.addEventListener('click', (e) => {
        e.stopPropagation();
        a.on = !a.on;
        if (state.snooze && state.snooze.id === a.id && !a.on) state.snooze = null;
        save(); renderList();
      });
      row.addEventListener('click', () => openEditor(a));
      list.appendChild(row);
    });
    renderNext();
  }

  let editing = null, draft = null;
  function openEditor(a) {
    editing = a || null;
    draft = a ? JSON.parse(JSON.stringify(a)) : { id: Date.now().toString(36), h: 7, m: 0, days: [1, 2, 3, 4, 5], label: '', tone: 'chimes', snooze: 9, on: true };
    $('adTitle').textContent = a ? 'Edit alarm' : 'New alarm';
    $('adTime').value = pad(draft.h) + ':' + pad(draft.m);
    $('adLabel').value = draft.label;
    $('adDelete').style.display = a ? '' : 'none';
    refreshEditor();
    $('alarmDialog').className = 'overlay';
  }
  function closeEditor() { stopSound(); $('alarmDialog').className = 'overlay hidden'; }
  function refreshEditor() {
    Array.prototype.forEach.call($('adDays').querySelectorAll('button'), (b) => {
      b.className = draft.days.indexOf(+b.getAttribute('data-d')) >= 0 ? 'on' : '';
    });
    Array.prototype.forEach.call($('adTones').querySelectorAll('.tone'), (b) => {
      b.className = 'tone' + (b.getAttribute('data-t') === draft.tone ? ' on' : '');
    });
    Array.prototype.forEach.call($('adSnooze').querySelectorAll('button'), (b) => {
      b.className = +b.getAttribute('data-v') === draft.snooze ? 'on' : '';
    });
  }

  function init(o) {
    opts = Object.assign(opts, o || {});
    // build the editor controls
    const daysBox = $('adDays');
    [1, 2, 3, 4, 5, 6, 0].forEach((d) => {
      const b = document.createElement('button');
      b.type = 'button'; b.setAttribute('data-d', d); b.textContent = DAYS[d].slice(0, 2);
      b.addEventListener('click', () => {
        const i = draft.days.indexOf(d);
        if (i >= 0) draft.days.splice(i, 1); else draft.days.push(d);
        refreshEditor();
      });
      daysBox.appendChild(b);
    });
    const tonesBox = $('adTones');
    TONES.forEach((t) => {
      const b = document.createElement('button');
      b.type = 'button'; b.className = 'tone'; b.setAttribute('data-t', t.id);
      b.innerHTML = '<span class="tone-play">&#9654;</span> ';
      b.appendChild(document.createTextNode(t.name));
      b.addEventListener('click', () => { draft.tone = t.id; refreshEditor(); unlock(); play(t.id, false); });
      tonesBox.appendChild(b);
    });
    Array.prototype.forEach.call($('adSnooze').querySelectorAll('button'), (b) => {
      b.addEventListener('click', () => { draft.snooze = +b.getAttribute('data-v'); refreshEditor(); });
    });
    $('addAlarm').addEventListener('click', () => openEditor(null));
    $('adCancel').addEventListener('click', closeEditor);
    $('adSave').addEventListener('click', () => {
      const v = ($('adTime').value || '07:00').split(':');
      draft.h = Math.min(23, Math.max(0, parseInt(v[0], 10) || 0));
      draft.m = Math.min(59, Math.max(0, parseInt(v[1], 10) || 0));
      draft.label = $('adLabel').value.trim().slice(0, 40);
      draft.on = true;
      delete state.fired[draft.id];
      if (editing) Object.assign(editing, draft); else state.alarms.push(draft);
      save(); closeEditor(); renderList();
    });
    $('adDelete').addEventListener('click', () => {
      if (!editing || !confirm('Delete this alarm?')) return;
      state.alarms = state.alarms.filter((x) => x.id !== editing.id);
      if (state.snooze && state.snooze.id === editing.id) state.snooze = null;
      save(); closeEditor(); renderList();
    });
    $('ringStop').addEventListener('click', (e) => { e.stopPropagation(); stopRing(); });
    $('ringSnooze').addEventListener('click', (e) => { e.stopPropagation(); snooze(); });
    $('alarmRing').addEventListener('click', () => {
      // a tap on the alarm screen also starts the sound if the iPad had blocked it
      if (ringing && ctx && ctx.state !== 'running') { unlock(); play(ringing.tone, true, 0.4); updateHint(); }
    });
    renderList();
    setInterval(check, 5000);
    setInterval(renderNext, 30000);
    document.addEventListener('visibilitychange', () => { if (document.visibilityState === 'visible') check(); });
    check();
  }

  window.Alarm = {
    init: init,
    hasEnabled: () => state.alarms.some((a) => a.on) || !!state.snooze,
    refresh: renderList,
    // for testing
    _ring: (i) => ring(state.alarms[i || 0]),
    _state: () => state
  };
})();
